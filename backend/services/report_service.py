from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def create_pdf_report(file_path, image, detections):

    doc = SimpleDocTemplate(
        file_path,
        pagesize=A4
    )

    styles = getSampleStyleSheet()

    elements = []

    # Title
    elements.append(
        Paragraph(
            "Sonar Anomaly Detection Report",
            styles["Title"]
        )
    )

    elements.append(Spacer(1, 15))

    # Image information
    elements.append(
        Paragraph(
            f"<b>Source Image:</b> {image['original_filename']}",
            styles["Normal"]
        )
    )

    elements.append(
        Paragraph(
            f"<b>Image ID:</b> {image['id']}",
            styles["Normal"]
        )
    )

    elements.append(
        Paragraph(
            f"<b>Status:</b> {image['status']}",
            styles["Normal"]
        )
    )

    elements.append(Spacer(1, 15))

    # Summary
    total = len(detections)

    accepted = sum(
        1 for d in detections
        if d["filter_status"] == "accepted"
    )

    rejected = sum(
        1 for d in detections
        if d["filter_status"] == "rejected"
    )

    pending = sum(
        1 for d in detections
        if d["filter_status"] == "pending"
    )

    elements.append(
        Paragraph(
            "<b>Detection Summary</b>",
            styles["Heading2"]
        )
    )

    summary_data = [
        ["Total", "Accepted", "Rejected", "Pending"],
        [total, accepted, rejected, pending]
    ]

    summary_table = Table(summary_data)

    summary_table.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 1, colors.black),
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ])
    )

    elements.append(summary_table)

    elements.append(Spacer(1, 20))

    # Detection details
    elements.append(
        Paragraph(
            "<b>Detected Anomalies</b>",
            styles["Heading2"]
        )
    )

    table_data = [
        [
            "ID",
            "Class",
            "Confidence",
            "Status",
            "Bounding Box",
            "Latitude",
            "Longitude"
        ]
    ]

    for d in detections:

        confidence = (
            f"{d['model_confidence'] * 100:.1f}%"
            if d["model_confidence"] is not None
            else "N/A"
        )

        bbox = (
            f"({d['x1']}, {d['y1']}) - "
            f"({d['x2']}, {d['y2']})"
        )

        latitude = (
            str(d["latitude"])
            if d["latitude"] is not None
            else "N/A"
        )

        longitude = (
            str(d["longitude"])
            if d["longitude"] is not None
            else "N/A"
        )

        table_data.append([
            d["id"],
            d["class_name"],
            confidence,
            d["filter_status"],
            bbox,
            latitude,
            longitude
        ])

    detection_table = Table(
        table_data,
        repeatRows=1
    )

    detection_table.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("FONTSIZE", (0, 0), (-1, -1), 7),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )

    elements.append(detection_table)

    elements.append(Spacer(1, 20))

    elements.append(
        Paragraph(
            "This report was automatically generated by the Cognitia sonar anomaly detection system.",
            styles["Normal"]
        )
    )

    doc.build(elements)